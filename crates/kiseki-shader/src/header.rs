//! `KISEKI_*` macro header generation (RFC-0004 §1.2).
//!
//! Every theme-specific constant becomes a preprocessor macro so a single
//! template covers all three dynamic quality tiers, and so `kiseki bg`,
//! `kiseki crt` and `kiseki compose` only need to re-emit this header.

use kiseki_schema::ResolvedTheme;

/// The shader language a header is generated for.
///
/// Only the vector constructor spelling differs: Ghostty's GLSL wants
/// `vec3(...)` and Windows Terminal's HLSL wants `float3(...)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShaderLanguage {
    Glsl,
    Hlsl,
}

impl ShaderLanguage {
    /// Name of the three-component vector constructor for this language.
    pub const fn vec3(self) -> &'static str {
        match self {
            Self::Glsl => "vec3",
            Self::Hlsl => "float3",
        }
    }
}

/// Values that vary per invocation rather than per theme.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HeaderParams {
    /// Opacity of the wallpaper layer, `0.0..=1.0`.
    pub bg_opacity: f64,
    /// Alpha of the composited background layer, `0.0..=1.0`.
    pub window_alpha: f64,
    /// Emit `KISEKI_ENABLE_CRT 1`.
    pub crt: bool,
}

impl HeaderParams {
    /// Reads opacity values from a resolved theme.
    pub fn from_theme(theme: &ResolvedTheme) -> Self {
        Self {
            bg_opacity: theme.wallpaper_opacity.unwrap_or(1.0).clamp(0.0, 1.0),
            window_alpha: theme.window_opacity.clamp(0.0, 1.0),
            crt: theme.crt_enabled,
        }
    }
}

/// Builds the macro header block, terminated by a newline.
///
/// The output is deterministic for a given `(theme, params, language)` triple,
/// which is what makes the compiled shader artefacts reproducible.
pub fn build_header(theme: &ResolvedTheme, params: HeaderParams, language: ShaderLanguage) -> String {
    let (br, bg, bb) = theme.base_bg().to_unit_rgb();
    let (pr, pg, pb) = theme.palette.accents.primary.to_unit_rgb();
    let (sr, sg, sb) = theme.palette.accents.secondary.to_unit_rgb();
    let vector = language.vec3();

    let mut out = String::with_capacity(1024);
    out.push_str("// === Auto-generated by Kiseki Shader Preprocessor (DO NOT EDIT) ===\n");
    out.push_str(&format!(
        "// theme: {} | profile: {}\n",
        theme.id, theme.profile
    ));
    out.push_str(&format!(
        "#define KISEKI_QUALITY_LEVEL {}\n",
        theme.profile.quality_level()
    ));
    out.push_str(&format!("#define KISEKI_BASE_BG {vector}({br:.6}, {bg:.6}, {bb:.6})\n"));
    out.push_str(&format!(
        "#define KISEKI_ACCENT_PRIMARY {vector}({pr:.6}, {pg:.6}, {pb:.6})\n"
    ));
    out.push_str(&format!(
        "#define KISEKI_ACCENT_SECONDARY {vector}({sr:.6}, {sg:.6}, {sb:.6})\n"
    ));
    out.push_str(&format!("#define KISEKI_BG_OPACITY {:.4}\n", params.bg_opacity));
    out.push_str(&format!("#define KISEKI_WINDOW_ALPHA {:.4}\n", params.window_alpha));
    out.push_str(&format!(
        "#define KISEKI_SAFE_ZONE_END_X {:.4}\n",
        theme.safe_zone_end_x()
    ));
    out.push_str(&format!(
        "#define KISEKI_NARROW_FADE_ASPECT {:.4}\n",
        theme.narrow_fade_aspect()
    ));
    out.push_str(&format!(
        "#define KISEKI_ENABLE_CRT {}\n",
        u8::from(params.crt)
    ));

    // Theme custom params, sorted by name for reproducible output.
    if let Some(shader) = theme.atmosphere.shader.as_ref() {
        for (name, value) in &shader.params {
            out.push_str(&format!(
                "#define KISEKI_PARAM_{} {}\n",
                to_macro_case(name),
                value.to_glsl_literal()
            ));
        }
    }

    out.push_str("// === End Kiseki Header ===\n");
    out
}

/// Shared helper snippets injected after the header and before the template.
///
/// Providing these centrally is what keeps `bgLayerMask` and narrow-pane
/// handling identical across every theme (RFC-0004 §2.1).
pub const HELPERS_GLSL: &str = r#"
// --- Kiseki shared GLSL helpers (injected) --------------------------------
// Text-protection weight in 0..1: 1.0 over pure background, -> 0.0 over glyphs.
float kiseki_bg_mask(vec4 term, vec2 uv) {
    vec3 unpremul = term.rgb / max(term.a, 0.001);
    float diff = length(unpremul - KISEKI_BASE_BG);
    float luma = dot(unpremul, vec3(0.299, 0.587, 0.114));
    float codeZone = 1.0 - smoothstep(KISEKI_SAFE_ZONE_END_X - 0.02, KISEKI_SAFE_ZONE_END_X + 0.18, uv.x);
    float glyph = smoothstep(0.22, 0.48, luma) * smoothstep(0.18, 0.42, diff);
    return 1.0 - glyph * mix(0.42, 0.88, codeZone);
}

// Aspect-ratio fade: 0.0 in narrow split panes, 1.0 on wide windows.
float kiseki_narrow_factor(vec2 res) {
    float aspect = res.x / max(res.y, 1.0);
    return smoothstep(0.65, KISEKI_NARROW_FADE_ASPECT, aspect);
}
// --- End Kiseki shared helpers --------------------------------------------
"#;

/// Shared helper snippets for the HLSL template.
pub const HELPERS_HLSL: &str = r#"
// --- Kiseki shared HLSL helpers (injected) --------------------------------
// Aspect-ratio fade: 0.0 in narrow split panes, 1.0 on wide windows.
float kiseki_narrow_factor(float2 res) {
    float aspect = res.x / max(res.y, 1.0);
    return smoothstep(0.65, KISEKI_NARROW_FADE_ASPECT, aspect);
}
// --- End Kiseki shared helpers --------------------------------------------
"#;

/// Converts `scanPeriodSec` to `SCAN_PERIOD_SEC` for macro naming.
pub fn to_macro_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (index, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() && index > 0 {
            let previous_lower = name.chars().nth(index - 1).is_some_and(|c| c.is_ascii_lowercase());
            if previous_lower {
                out.push('_');
            }
        }
        out.push(ch.to_ascii_uppercase());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::ResolvedTheme;
    use kiseki_types::RenderingProfile;

    fn theme(profile: RenderingProfile) -> ResolvedTheme {
        let pack: kiseki_schema::ThemePack = kiseki_schema::ThemePack {
            manifest: serde_json::from_str(include_str!(
                "../../../themes/nerv-eva/manifest.json"
            ))
            .unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json"))
                .unwrap(),
        };
        ResolvedTheme::from_pack(&pack, profile)
    }

    #[test]
    fn header_declares_every_required_macro() {
        let theme = theme(RenderingProfile::Balanced);
        let header = build_header(&theme, HeaderParams::from_theme(&theme), ShaderLanguage::Glsl);
        for macro_name in [
            "KISEKI_QUALITY_LEVEL",
            "KISEKI_BASE_BG",
            "KISEKI_ACCENT_PRIMARY",
            "KISEKI_ACCENT_SECONDARY",
            "KISEKI_BG_OPACITY",
            "KISEKI_WINDOW_ALPHA",
            "KISEKI_SAFE_ZONE_END_X",
            "KISEKI_NARROW_FADE_ASPECT",
            "KISEKI_ENABLE_CRT",
            "KISEKI_PARAM_SCAN_PERIOD_SEC",
            "KISEKI_PARAM_GLITCH_INTERVAL_SEC",
            "KISEKI_PARAM_HEARTBEAT_HZ",
            "KISEKI_PARAM_HEX_CELL_PX",
        ] {
            assert!(header.contains(&format!("#define {macro_name} ")), "missing {macro_name}");
        }
        assert!(header.starts_with("// === Auto-generated"));
        assert!(header.trim_end().ends_with("// === End Kiseki Header ==="));
    }

    #[test]
    fn quality_level_tracks_profile() {
        for (profile, level) in [
            (RenderingProfile::Eco, "1"),
            (RenderingProfile::Balanced, "2"),
            (RenderingProfile::Ultra, "3"),
        ] {
            let theme = theme(profile);
            let header = build_header(&theme, HeaderParams::from_theme(&theme), ShaderLanguage::Glsl);
            assert!(
                header.contains(&format!("#define KISEKI_QUALITY_LEVEL {level}\n")),
                "{profile} -> {header}"
            );
        }
    }

    #[test]
    fn colors_are_rendered_as_unit_vectors() {
        let theme = theme(RenderingProfile::Balanced);
        let header = build_header(&theme, HeaderParams::from_theme(&theme), ShaderLanguage::Glsl);
        // #0B090A -> 11/255, 9/255, 10/255
        assert!(header.contains("#define KISEKI_BASE_BG vec3(0.043137, 0.035294, 0.039216)"), "{header}");
        assert!(header.contains("#define KISEKI_ACCENT_PRIMARY vec3(0.941176, 0.415686, 0.133333)"), "{header}");
    }

    #[test]
    fn hlsl_header_uses_float3_vectors() {
        let theme = theme(RenderingProfile::Balanced);
        let header = build_header(&theme, HeaderParams::from_theme(&theme), ShaderLanguage::Hlsl);
        for macro_name in ["KISEKI_BASE_BG", "KISEKI_ACCENT_PRIMARY", "KISEKI_ACCENT_SECONDARY"] {
            assert!(
                header.contains(&format!("#define {macro_name} float3(")),
                "{macro_name} must use float3 in HLSL:\n{header}"
            );
        }
        assert!(!header.contains("vec3("), "{header}");
        // Non-vector macros are language-independent.
        assert!(header.contains("#define KISEKI_BG_OPACITY "));
    }

    #[test]
    fn header_is_deterministic() {
        let theme = theme(RenderingProfile::Ultra);
        let params = HeaderParams::from_theme(&theme);
        assert_eq!(
            build_header(&theme, params, ShaderLanguage::Glsl),
            build_header(&theme, params, ShaderLanguage::Glsl)
        );
    }

    #[test]
    fn crt_and_opacity_overrides_reach_the_header() {
        let theme = theme(RenderingProfile::Balanced);
        let header = build_header(
            &theme,
            HeaderParams {
                bg_opacity: 0.55,
                window_alpha: 0.9,
                crt: true,
            },
            ShaderLanguage::Glsl,
        );
        assert!(header.contains("#define KISEKI_BG_OPACITY 0.5500"));
        assert!(header.contains("#define KISEKI_WINDOW_ALPHA 0.9000"));
        assert!(header.contains("#define KISEKI_ENABLE_CRT 1"));
    }

    #[test]
    fn macro_case_conversion() {
        assert_eq!(to_macro_case("scanPeriodSec"), "SCAN_PERIOD_SEC");
        assert_eq!(to_macro_case("narrowFadeAspect"), "NARROW_FADE_ASPECT");
        assert_eq!(to_macro_case("hex"), "HEX");
        assert_eq!(to_macro_case("hexCellPx"), "HEX_CELL_PX");
    }

    #[test]
    fn helpers_use_ordered_smoothstep_edges() {
        for helper in [HELPERS_GLSL, HELPERS_HLSL] {
            let lint = crate::lint::lint_source(helper);
            assert!(lint.diagnostics.iter().all(|d| !d.is_fatal()), "{:?}", lint.diagnostics);
        }
    }
}

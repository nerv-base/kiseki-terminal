#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::ThemePack;
    use kiseki_types::RenderingProfile;

    fn theme() -> ResolvedTheme {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json"))
                .unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json"))
                .unwrap(),
        };
        ResolvedTheme::from_pack(&pack, RenderingProfile::Balanced)
    }

    #[test]
    fn renders_all_tier2_formats_cleanly() {
        let t = theme();

        let nvim = render_neovim(&t);
        assert!(nvim.contains("vim.g.colors_name = 'kiseki'"));
        assert!(nvim.contains("@keyword"));

        let vim = render_vim(&t);
        assert!(vim.contains("let g:colors_name = 'kiseki'"));
        assert!(vim.contains("g:terminal_ansi_colors"));

        let helix = render_helix(&t);
        assert!(toml::from_str::<toml::Value>(&helix).is_ok(), "invalid helix toml:\n{helix}");

        let tmux = render_tmux(&t);
        assert!(tmux.contains("status-style"));
        assert!(tmux.contains("pane-active-border-style"));

        let zellij = render_zellij(&t);
        assert!(zellij.contains("themes {"));
        assert!(zellij.contains("kiseki {"));

        let opencode = render_opencode(&t);
        let parsed: serde_json::Value = serde_json::from_str(&opencode).unwrap();
        assert_eq!(parsed["defs"]["base"], "#0B090A");

        let bat = render_bat_tmtheme(&t);
        assert!(bat.starts_with("<?xml version=\"1.0\""));
        assert!(bat.contains("<plist version=\"1.0\">"));
        assert!(bat.contains("Kiseki (NERV UNIT-02)"));

        let delta = render_delta(&t);
        assert!(delta.contains("[delta \"kiseki\"]"));

        let lazygit = render_lazygit(&t);
        assert!(lazygit.contains("activeBorderColor:"));

        let btop = render_btop(&t);
        assert!(btop.contains("theme[main_bg]=\"#0B090A\""));
    }
}

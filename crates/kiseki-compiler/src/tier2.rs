//! Tier 2 ecosystem artefact compilers (RFC-0003 §4).
//!
//! Pure, deterministic functions turning a [`ResolvedTheme`] into native theme
//! artefacts for Neovim, Vim, Helix, tmux, Zellij, OpenCode, bat (`.tmTheme`
//! TextMate XML), git-delta, lazygit and btop.

use kiseki_schema::ResolvedTheme;
use kiseki_types::Appearance;

use crate::escape::toml_string;

/// Renders `generated/nvim/kiseki.lua` (Neovim `nvim_set_hl` + Treesitter + LSP).
pub fn render_neovim(theme: &ResolvedTheme) -> String {
    let p = &theme.palette;
    let s = &theme.syntax;
    let d = &theme.diff;
    let u = &theme.ui;
    let ansi = p.ansi.as_indexed();
    let bg_mode = match theme.appearance {
        Appearance::Dark => "dark",
        Appearance::Light => "light",
    };

    let mut out = String::with_capacity(4096);
    out.push_str("-- === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("-- theme: {} | profile: {}\n\n", theme.id, theme.profile));
    out.push_str("vim.cmd('highlight clear')\n");
    out.push_str("if vim.fn.exists('syntax_on') == 1 then vim.cmd('syntax reset') end\n");
    out.push_str("vim.o.termguicolors = true\n");
    out.push_str(&format!("vim.o.background = '{bg_mode}'\n"));
    out.push_str("vim.g.colors_name = 'kiseki'\n\n");

    for (idx, color) in ansi.iter().enumerate() {
        out.push_str(&format!("vim.g.terminal_color_{idx} = '{}'\n", color.to_hex()));
    }

    out.push_str("\nlocal hl = function(group, opts) vim.api.nvim_set_hl(0, group, opts) end\n");
    let groups: &[(&str, String)] = &[
        ("Normal", format!("{{ fg = '{}', bg = '{}' }}", p.text.primary, p.surfaces.base)),
        ("NormalFloat", format!("{{ fg = '{}', bg = '{}' }}", p.text.primary, p.surfaces.mantle)),
        ("FloatBorder", format!("{{ fg = '{}', bg = '{}' }}", u.border_focused, p.surfaces.mantle)),
        ("WinSeparator", format!("{{ fg = '{}' }}", u.border)),
        ("Cursor", format!("{{ fg = '{}', bg = '{}' }}", p.interaction.cursor_text, p.interaction.cursor)),
        ("CursorLine", format!("{{ bg = '{}' }}", p.surfaces.surface0)),
        ("CursorLineNr", format!("{{ fg = '{}', bold = true }}", p.accents.primary)),
        ("LineNr", format!("{{ fg = '{}' }}", p.text.muted)),
        ("Visual", format!("{{ fg = '{}', bg = '{}' }}", p.interaction.selection_fg, p.interaction.selection_bg)),
        ("Search", format!("{{ fg = '{}', bg = '{}' }}", p.interaction.match_fg, p.interaction.match_bg)),
        ("IncSearch", format!("{{ fg = '{}', bg = '{}', bold = true }}", p.text.inverse, p.accents.primary)),
        ("StatusLine", format!("{{ fg = '{}', bg = '{}' }}", u.statusline_fg, u.statusline_bg)),
        ("StatusLineNC", format!("{{ fg = '{}', bg = '{}' }}", p.text.muted, p.surfaces.crust)),
        ("TabLine", format!("{{ fg = '{}', bg = '{}' }}", u.tab_inactive_fg, u.tab_inactive_bg)),
        ("TabLineSel", format!("{{ fg = '{}', bg = '{}', bold = true }}", u.tab_active_fg, u.tab_active_bg)),
        ("TabLineFill", format!("{{ bg = '{}' }}", p.surfaces.crust)),
        ("Pmenu", format!("{{ fg = '{}', bg = '{}' }}", p.text.primary, p.surfaces.surface0)),
        ("PmenuSel", format!("{{ fg = '{}', bg = '{}', bold = true }}", p.text.inverse, p.accents.primary)),
        ("Comment", format!("{{ fg = '{}', italic = true }}", s.comment)),
        ("Keyword", format!("{{ fg = '{}', bold = true }}", s.keyword)),
        ("Operator", format!("{{ fg = '{}' }}", s.operator)),
        ("Function", format!("{{ fg = '{}' }}", s.function)),
        ("Type", format!("{{ fg = '{}' }}", s.type_)),
        ("Identifier", format!("{{ fg = '{}' }}", s.variable)),
        ("String", format!("{{ fg = '{}' }}", s.string)),
        ("SpecialChar", format!("{{ fg = '{}' }}", s.escape)),
        ("Number", format!("{{ fg = '{}' }}", s.number)),
        ("Boolean", format!("{{ fg = '{}' }}", s.boolean)),
        ("Constant", format!("{{ fg = '{}' }}", s.constant)),
        ("Delimiter", format!("{{ fg = '{}' }}", s.punctuation)),
        ("Tag", format!("{{ fg = '{}' }}", s.tag)),
        ("PreProc", format!("{{ fg = '{}' }}", s.macro_)),
        ("Error", format!("{{ fg = '{}', bold = true }}", s.invalid)),
        ("DiffAdd", format!("{{ fg = '{}', bg = '{}' }}", d.add_fg, d.add_bg)),
        ("DiffDelete", format!("{{ fg = '{}', bg = '{}' }}", d.delete_fg, d.delete_bg)),
        ("DiffChange", format!("{{ fg = '{}', bg = '{}' }}", d.change_fg, d.change_bg)),
        ("DiagnosticError", format!("{{ fg = '{}' }}", p.semantic.error)),
        ("DiagnosticWarn", format!("{{ fg = '{}' }}", p.semantic.warning)),
        ("DiagnosticInfo", format!("{{ fg = '{}' }}", p.semantic.info)),
        ("DiagnosticHint", format!("{{ fg = '{}' }}", p.semantic.hint)),
        // Treesitter core captures
        ("@comment", "{ link = 'Comment' }".to_string()),
        ("@keyword", "{ link = 'Keyword' }".to_string()),
        ("@operator", "{ link = 'Operator' }".to_string()),
        ("@function", "{ link = 'Function' }".to_string()),
        ("@function.method", format!("{{ fg = '{}' }}", s.method)),
        ("@type", "{ link = 'Type' }".to_string()),
        ("@variable", "{ link = 'Identifier' }".to_string()),
        ("@variable.parameter", format!("{{ fg = '{}' }}", s.parameter)),
        ("@property", format!("{{ fg = '{}' }}", s.property)),
        ("@string", "{ link = 'String' }".to_string()),
        ("@string.escape", "{ link = 'SpecialChar' }".to_string()),
        ("@number", "{ link = 'Number' }".to_string()),
        ("@boolean", "{ link = 'Boolean' }".to_string()),
        ("@constant", "{ link = 'Constant' }".to_string()),
        ("@punctuation", "{ link = 'Delimiter' }".to_string()),
        ("@tag", "{ link = 'Tag' }".to_string()),
        ("@attribute", format!("{{ fg = '{}' }}", s.attribute)),
        ("@function.macro", "{ link = 'PreProc' }".to_string()),
    ];
    for (name, spec) in groups {
        out.push_str(&format!("hl('{name}', {spec})\n"));
    }
    out
}

/// Renders `generated/vim/kiseki.vim`.
pub fn render_vim(theme: &ResolvedTheme) -> String {
    let p = &theme.palette;
    let s = &theme.syntax;
    let d = &theme.diff;
    let u = &theme.ui;
    let ansi = p.ansi.as_indexed();
    let bg_mode = match theme.appearance {
        Appearance::Dark => "dark",
        Appearance::Light => "light",
    };

    let mut out = String::with_capacity(2048);
    out.push_str("\" === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("\" theme: {} | profile: {}\n\n", theme.id, theme.profile));
    out.push_str("highlight clear\n");
    out.push_str("if exists('syntax_on') | syntax reset | endif\n");
    out.push_str(&format!("set background={bg_mode}\n"));
    out.push_str("if has('termguicolors') | set termguicolors | endif\n");
    out.push_str("let g:colors_name = 'kiseki'\n");
    let ansi_list = ansi
        .iter()
        .map(|c| format!("'{}'", c.to_hex()))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(&format!("let g:terminal_ansi_colors = [{ansi_list}]\n\n"));

    for line in [
        format!("hi Normal guifg={} guibg={}", p.text.primary, p.surfaces.base),
        format!("hi CursorLine guibg={}", p.surfaces.surface0),
        format!("hi CursorLineNr guifg={} gui=bold", p.accents.primary),
        format!("hi LineNr guifg={}", p.text.muted),
        format!("hi Visual guifg={} guibg={}", p.interaction.selection_fg, p.interaction.selection_bg),
        format!("hi Search guifg={} guibg={}", p.interaction.match_fg, p.interaction.match_bg),
        format!("hi StatusLine guifg={} guibg={}", u.statusline_fg, u.statusline_bg),
        format!("hi VertSplit guifg={}", u.border),
        format!("hi Comment guifg={} gui=italic", s.comment),
        format!("hi Keyword guifg={} gui=bold", s.keyword),
        format!("hi Statement guifg={} gui=bold", s.keyword),
        format!("hi Operator guifg={}", s.operator),
        format!("hi Function guifg={}", s.function),
        format!("hi Type guifg={}", s.type_),
        format!("hi Identifier guifg={}", s.variable),
        format!("hi String guifg={}", s.string),
        format!("hi Number guifg={}", s.number),
        format!("hi Boolean guifg={}", s.boolean),
        format!("hi Constant guifg={}", s.constant),
        format!("hi PreProc guifg={}", s.macro_),
        format!("hi Error guifg={} gui=bold", s.invalid),
        format!("hi DiffAdd guifg={} guibg={}", d.add_fg, d.add_bg),
        format!("hi DiffDelete guifg={} guibg={}", d.delete_fg, d.delete_bg),
        format!("hi DiffChange guifg={} guibg={}", d.change_fg, d.change_bg),
    ] {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Renders `generated/helix/kiseki.toml`.
pub fn render_helix(theme: &ResolvedTheme) -> String {
    let p = &theme.palette;
    let s = &theme.syntax;
    let d = &theme.diff;
    let u = &theme.ui;

    let mut out = String::with_capacity(2048);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n\n", theme.id, theme.profile));

    out.push_str(&format!("\"ui.background\" = {{ bg = {} }}\n", toml_string(&p.surfaces.base.to_hex())));
    out.push_str(&format!("\"ui.text\" = {{ fg = {} }}\n", toml_string(&p.text.primary.to_hex())));
    out.push_str(&format!("\"ui.text.focus\" = {{ fg = {}, modifiers = [\"bold\"] }}\n", toml_string(&p.accents.primary.to_hex())));
    out.push_str(&format!("\"ui.cursor\" = {{ fg = {}, bg = {} }}\n", toml_string(&p.interaction.cursor_text.to_hex()), toml_string(&p.interaction.cursor.to_hex())));
    out.push_str(&format!("\"ui.selection\" = {{ fg = {}, bg = {} }}\n", toml_string(&p.interaction.selection_fg.to_hex()), toml_string(&p.interaction.selection_bg.to_hex())));
    out.push_str(&format!("\"ui.linenr\" = {{ fg = {} }}\n", toml_string(&p.text.muted.to_hex())));
    out.push_str(&format!("\"ui.linenr.selected\" = {{ fg = {}, modifiers = [\"bold\"] }}\n", toml_string(&p.accents.primary.to_hex())));
    out.push_str(&format!("\"ui.statusline\" = {{ fg = {}, bg = {} }}\n", toml_string(&u.statusline_fg.to_hex()), toml_string(&u.statusline_bg.to_hex())));
    out.push_str(&format!("\"ui.statusline.inactive\" = {{ fg = {}, bg = {} }}\n", toml_string(&p.text.muted.to_hex()), toml_string(&p.surfaces.crust.to_hex())));
    out.push_str(&format!("\"ui.popup\" = {{ fg = {}, bg = {} }}\n", toml_string(&p.text.primary.to_hex()), toml_string(&p.surfaces.mantle.to_hex())));
    out.push_str(&format!("\"ui.window\" = {{ fg = {} }}\n", toml_string(&u.border.to_hex())));
    out.push_str(&format!("\"ui.menu\" = {{ fg = {}, bg = {} }}\n", toml_string(&p.text.primary.to_hex()), toml_string(&p.surfaces.surface0.to_hex())));
    out.push_str(&format!("\"ui.menu.selected\" = {{ fg = {}, bg = {} }}\n\n", toml_string(&p.text.inverse.to_hex()), toml_string(&p.accents.primary.to_hex())));

    for (scope, color) in [
        ("comment", s.comment),
        ("keyword", s.keyword),
        ("operator", s.operator),
        ("function", s.function),
        ("function.method", s.method),
        ("function.macro", s.macro_),
        ("type", s.type_),
        ("variable", s.variable),
        ("variable.parameter", s.parameter),
        ("variable.other.member", s.property),
        ("string", s.string),
        ("constant.character.escape", s.escape),
        ("constant.numeric", s.number),
        ("constant.builtin.boolean", s.boolean),
        ("constant", s.constant),
        ("punctuation", s.punctuation),
        ("tag", s.tag),
        ("attribute", s.attribute),
        ("diff.plus", d.add_fg),
        ("diff.minus", d.delete_fg),
        ("diff.delta", d.change_fg),
        ("error", p.semantic.error),
        ("warning", p.semantic.warning),
        ("info", p.semantic.info),
        ("hint", p.semantic.hint),
    ] {
        out.push_str(&format!("\"{scope}\" = {}\n", toml_string(&color.to_hex())));
    }
    out
}

/// Renders `generated/tmux.conf` (statusline, borders, messages, copy-mode).
pub fn render_tmux(theme: &ResolvedTheme) -> String {
    let p = &theme.palette;
    let u = &theme.ui;
    let mut out = String::with_capacity(1024);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n\n", theme.id, theme.profile));
    out.push_str(&format!(
        "set -g status-style \"bg={},fg={}\"\n",
        u.statusline_bg, u.statusline_fg
    ));
    out.push_str(&format!(
        "set -g window-status-style \"bg={},fg={}\"\n",
        u.tab_inactive_bg, u.tab_inactive_fg
    ));
    out.push_str(&format!(
        "set -g window-status-current-style \"bg={},fg={},bold\"\n",
        u.tab_active_bg, u.tab_active_fg
    ));
    out.push_str(&format!("set -g pane-border-style \"fg={}\"\n", u.border));
    out.push_str(&format!(
        "set -g pane-active-border-style \"fg={}\"\n",
        u.border_focused
    ));
    out.push_str(&format!(
        "set -g message-style \"bg={},fg={}\"\n",
        p.surfaces.surface1, p.accents.primary
    ));
    out.push_str(&format!(
        "set -g mode-style \"bg={},fg={}\"\n",
        p.interaction.selection_bg, p.interaction.selection_fg
    ));
    out
}


//! macOS Terminal.app AppleScript generation (RFC-0003 §4).
//!
//! Per RFC-0003, Apple Terminal is a low-priority adapter that only runs when
//! the user is actively inside `Apple_Terminal` or explicitly requests
//! `--only apple-terminal`. Only visual colour and typography properties are
//! emitted; `do shell script` is strictly forbidden.

use kiseki_schema::ResolvedTheme;
use kiseki_types::{Color, Diagnostic};

fn applescript_string(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len() + 2);
    out.push('"');
    for ch in raw.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            ch if ch.is_control() => {}
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn rgb16(color: Color) -> String {
    let r = u32::from(color.r()) * 257;
    let g = u32::from(color.g()) * 257;
    let b = u32::from(color.b()) * 257;
    format!("{{{r}, {g}, {b}}}")
}

/// Renders `generated/apple-terminal.applescript`.
pub fn render(
    theme: &ResolvedTheme,
    font_families: &[String],
    macos_font_scale: bool,
) -> String {
    let palette = &theme.palette;
    let mut out = String::with_capacity(1024);
    out.push_str("-- === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("-- theme: {} | profile: {}\n", theme.id, theme.profile));
    out.push_str("tell application \"Terminal\"\n");
    out.push_str("  set targetSettings to default settings\n");
    out.push_str(&format!(
        "  set background color of targetSettings to {}\n",
        rgb16(palette.surfaces.base)
    ));
    out.push_str(&format!(
        "  set normal text color of targetSettings to {}\n",
        rgb16(palette.text.primary)
    ));
    out.push_str(&format!(
        "  set bold text color of targetSettings to {}\n",
        rgb16(palette.accents.primary)
    ));
    out.push_str(&format!(
        "  set cursor color of targetSettings to {}\n",
        rgb16(palette.interaction.cursor)
    ));
    if let Some(primary) = font_families.first() {
        out.push_str(&format!(
            "  set font name of targetSettings to {}\n",
            applescript_string(primary)
        ));
    }
    if let Some(size) = theme.typography.size_pt {
        let effective = if macos_font_scale {
            (size * 1.25 * 2.0).round() / 2.0
        } else {
            size
        };
        out.push_str(&format!("  set font size of targetSettings to {effective:.1}\n"));
    }
    out.push_str("  repeat with w in windows\n");
    out.push_str("    repeat with t in tabs of w\n");
    out.push_str("      set current settings of t to targetSettings\n");
    out.push_str("    end repeat\n");
    out.push_str("  end repeat\n");
    out.push_str("end tell\n");
    out
}

/// Static validation: never emit `do shell script`.
pub fn lint(content: &str) -> Vec<Diagnostic> {
    let mut diagnostics = Vec::new();
    if content.to_ascii_lowercase().contains("do shell script") {
        diagnostics.push(Diagnostic::error(
            "adapter.apple-terminal.forbidden",
            "generated apple-terminal.applescript must never execute shell commands",
        ));
    }
    diagnostics
}

#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::ThemePack;
    use kiseki_types::RenderingProfile;

    #[test]
    fn renders_visual_only_applescript() {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json"))
                .unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json"))
                .unwrap(),
        };
        let theme = ResolvedTheme::from_pack(&pack, RenderingProfile::Balanced);
        let script = render(&theme, &["JetBrainsMono Nerd Font".to_string()], true);
        assert!(script.contains("tell application \"Terminal\""));
        assert!(script.contains("background color"));
        assert!(script.contains("JetBrainsMono Nerd Font"));
        assert!(lint(&script).is_empty());
    }
}

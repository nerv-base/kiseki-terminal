//! Ghostty `ghostty.conf` generation (RFC-0003 §4, RFC-0004 §2.1).
//!
//! Only visual keys are emitted. In particular this file never contains
//! `shell-integration-features`, `keybind`, `command` or `initial-command`:
//! Ghostty's shell integration is the user's business, not the theme's.

use std::path::Path;

use kiseki_schema::{CursorShape, ResolvedTheme};
use kiseki_types::{Diagnostic, Result};

use crate::escape::conf_value;

/// Renders the generated Ghostty config (without OS-specific font scaling).
pub fn render(
    theme: &ResolvedTheme,
    font_families: &[String],
    wallpaper: Option<&Path>,
    shader: Option<&Path>,
) -> Result<String> {
    render_with_scale(theme, font_families, wallpaper, shader, false)
}

/// Renders the generated Ghostty config, optionally scaling DirectWrite point
/// sizes to macOS CoreText (1.25x rounded to 0.5pt, matching v1).
pub fn render_with_scale(
    theme: &ResolvedTheme,
    font_families: &[String],
    wallpaper: Option<&Path>,
    shader: Option<&Path>,
    macos_font_scale: bool,
) -> Result<String> {
    let palette = &theme.palette;
    let mut out = String::with_capacity(2048);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n", theme.id, theme.profile));
    out.push_str("# Edit the theme tokens instead; `kiseki use` rewrites this file.\n\n");

    // Clear any built-in Ghostty `theme = ...` set earlier in the user's config
    // so our explicit palette & background always win cleanly.
    out.push_str("theme =\n");
    out.push_str(&format!("background = {}\n", palette.surfaces.base));
    out.push_str(&format!("foreground = {}\n", palette.text.primary));
    out.push_str(&format!("cursor-color = {}\n", palette.interaction.cursor));
    out.push_str(&format!("cursor-text = {}\n", palette.interaction.cursor_text));
    out.push_str(&format!(
        "selection-background = {}\n",
        palette.interaction.selection_bg
    ));
    out.push_str(&format!(
        "selection-foreground = {}\n",
        palette.interaction.selection_fg
    ));

    out.push('\n');
    for (index, color) in palette.ansi.as_indexed().iter().enumerate() {
        out.push_str(&format!("palette = {index}={color}\n"));
    }

    out.push('\n');
    out.push_str(&format!(
        "background-opacity = {:.4}\n",
        theme.window_opacity.clamp(0.0, 1.0)
    ));
    out.push_str("background-opacity-cells = false\n");
    if let Some(window) = theme.atmosphere.window.as_ref() {
        if let Some(unfocused) = window.unfocused_opacity {
            out.push_str(&format!("unfocused-split-opacity = {:.4}\n", unfocused));
        }
        if window.blur {
            out.push_str("background-blur = true\n");
        }
        if let Some(padding) = window.padding {
            out.push_str(&format!("window-padding-x = {}\n", padding.x));
            out.push_str(&format!("window-padding-y = {}\n", padding.y));
            out.push_str("window-padding-balance = true\n");
        }
    }
    if let Some(titlebar) = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.macos_titlebar_style)
    {
        out.push_str(&format!("macos-titlebar-style = {}\n", titlebar.as_str()));
    }

    out.push('\n');
    if !font_families.is_empty() {
        // Reset user fallback stack first so the theme's curated stack leads.
        out.push_str("font-family = \"\"\n");
        for family in font_families {
            out.push_str(&format!("font-family = {}\n", conf_value(family)?));
        }
    }
    if let Some(size) = theme.typography.size_pt {
        let effective = if macos_font_scale {
            (size * 1.25 * 2.0).round() / 2.0
        } else {
            size
        };
        out.push_str(&format!("font-size = {effective:.2}\n"));
    }
    match theme.typography.ligatures {
        Some(true) => out.push_str("font-feature = liga\n"),
        Some(false) => out.push_str("font-feature = -liga\n"),
        None => {}
    }

    let cursor = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.cursor_shape)
        .unwrap_or(CursorShape::Block);
    out.push_str(&format!("cursor-style = {}\n", ghostty_cursor(cursor)));
    if let Some(blink) = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.cursor_blink)
    {
        out.push_str(&format!("cursor-style-blink = {blink}\n"));
    }

    if let Some(wallpaper) = wallpaper.filter(|_| theme.wallpaper_opacity.is_none_or(|o| o > 0.0)) {
        let path = conf_value(&wallpaper.to_string_lossy())?;
        out.push_str(&format!("\nbackground-image = {path}\n"));
        if let Some(opacity) = theme.wallpaper_opacity {
            out.push_str(&format!("background-image-opacity = {opacity:.4}\n"));
        }
        let wallpaper_tokens = theme.atmosphere.wallpaper.as_ref();
        if let Some(alignment) = wallpaper_tokens.and_then(|wallpaper| wallpaper.alignment) {
            out.push_str(&format!(
                "background-image-position = {}\n",
                alignment.as_str()
            ));
        }
        if let Some(fit) = wallpaper_tokens.and_then(|wallpaper| wallpaper.fit) {
            out.push_str(&format!("background-image-fit = {}\n", fit.as_str()));
        }
        out.push_str("background-image-repeat = false\n");
    }

    if let Some(shader) = shader {
        let path = conf_value(&shader.to_string_lossy())?;
        out.push_str(&format!("\ncustom-shader = {path}\n"));
        out.push_str("custom-shader-animation = true\n");
    }

    Ok(out)
}

fn ghostty_cursor(shape: CursorShape) -> &'static str {
    match shape {
        CursorShape::Block => "block",
        CursorShape::BlockHollow => "block_hollow",
        CursorShape::Bar => "bar",
        CursorShape::Underline => "underline",
    }
}

/// Static validation of the generated file.
///
/// Runs even when the real `ghostty` binary is unavailable, so CI catches a
/// regression that would otherwise silently disable the user's shell
/// integration.
pub fn lint(content: &str) -> Vec<Diagnostic> {
    let mut diagnostics = Vec::new();
    for (index, line) in content.lines().enumerate() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some((key, value)) = trimmed.split_once('=') else {
            diagnostics.push(Diagnostic::error(
                "adapter.ghostty.syntax",
                format!("line {} is not `key = value`: {trimmed:?}", index + 1),
            ));
            continue;
        };
        let key = key.trim();
        let value = value.trim();
        const FORBIDDEN_KEYS: &[&str] = &[
            "shell-integration",
            "shell-integration-features",
            "keybind",
            "command",
            "initial-command",
            "working-directory",
        ];
        // Empty `theme =` intentionally clears a prior Ghostty preset theme so
        // Kiseki's explicit palette takes effect; setting a named theme is forbidden.
        if FORBIDDEN_KEYS.contains(&key) || (key == "theme" && !value.is_empty()) {
            diagnostics.push(Diagnostic::error(
                "adapter.ghostty.non-visual-key",
                format!("generated config must not set `{key}` (non-visual / behaviour altering)"),
            ));
        }
    }
    diagnostics
}

#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::{ThemePack, ResolvedTheme};
    use kiseki_types::RenderingProfile;
    use std::path::PathBuf;

    fn theme(profile: RenderingProfile) -> ResolvedTheme {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json")).unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json")).unwrap(),
        };
        ResolvedTheme::from_pack(&pack, profile)
    }

    #[test]
    fn config_carries_every_visual_family() {
        let theme = theme(RenderingProfile::Balanced);
        let content = render(
            &theme,
            &["JetBrainsMono Nerd Font".to_string()],
            Some(&PathBuf::from("/themes/nerv-eva/assets/wallpaper.png")),
            Some(&PathBuf::from("/cfg/generated/shaders/active.glsl")),
        )
        .unwrap();

        for needle in [
            "background = #0B090A",
            "foreground = #ECE4DA",
            "cursor-color = #F06A22",
            "palette = 0=#171214",
            "palette = 15=#FFF7F2",
            "background-opacity = 0.9500",
            "background-blur = true",
            "window-padding-x = 18",
            "font-family = JetBrainsMono Nerd Font",
            "font-size = 12.00",
            "font-feature = liga",
            "cursor-style = block",
            "background-image = /themes/nerv-eva/assets/wallpaper.png",
            "background-image-opacity = 0.7800",
            "background-image-position = bottom-right",
            "background-image-fit = cover",
            "custom-shader = /cfg/generated/shaders/active.glsl",
        ] {
            assert!(content.contains(needle), "missing {needle:?} in\n{content}");
        }
        assert!(lint(&content).is_empty(), "{:?}", lint(&content));
    }

    #[test]
    fn static_profile_omits_the_shader() {
        let theme = theme(RenderingProfile::Static);
        let content = render(&theme, &["monospace".to_string()], None, None).unwrap();
        assert!(!content.contains("custom-shader"));
        assert!(!content.contains("background-image"));
    }

    #[test]
    fn never_emits_shell_integration_or_keybinds() {
        let theme = theme(RenderingProfile::Ultra);
        let content = render(&theme, &["monospace".to_string()], None, None).unwrap();
        for forbidden in ["shell-integration", "keybind", "initial-command"] {
            assert!(!content.contains(forbidden), "{forbidden} leaked into\n{content}");
        }
    }

    #[test]
    fn lint_rejects_non_visual_keys() {
        let diagnostics = lint("shell-integration-features = no-cursor\nkeybind = ctrl+a=copy\n");
        assert_eq!(diagnostics.len(), 2);
        assert!(diagnostics.iter().all(Diagnostic::is_fatal));
        assert!(diagnostics
            .iter()
            .any(|diagnostic| diagnostic.code == "adapter.ghostty.non-visual-key"));
    }

    #[test]
    fn hostile_font_family_is_rejected() {
        let theme = theme(RenderingProfile::Balanced);
        let error = render(&theme, &["evil\nkeybind = x".to_string()], None, None).unwrap_err();
        assert!(error.to_string().contains("cannot be represented safely"));
    }
}

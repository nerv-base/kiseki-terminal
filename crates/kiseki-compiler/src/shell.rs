//! Shell environment artefacts and the zero-fork sync hook (RFC-0001 §5).
//!
//! Two invariants are tested here and must never regress:
//! 1. the generated `env.*` files contain no behaviour changes (no
//!    `alias cat`, no `zoxide init`, no key bindings);
//! 2. the `precmd`/`prompt` hook performs **zero** child-process forks on the
//!    no-change path: it only reads `state.gen` and compares a string.

use std::path::Path;

use kiseki_schema::ResolvedTheme;
use kiseki_types::PromptPolicy;

use crate::escape::{powershell_single_quote, shell_single_quote};

/// Shells the engine can emit an integration for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellKind {
    Zsh,
    Pwsh,
}

impl ShellKind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Zsh => "zsh",
            Self::Pwsh => "pwsh",
        }
    }

    pub const fn env_artifact(self) -> &'static str {
        match self {
            Self::Zsh => crate::artifact::names::ENV_ZSH,
            Self::Pwsh => crate::artifact::names::ENV_PS1,
        }
    }

    pub fn parse(raw: &str) -> Option<Self> {
        match raw.trim().to_ascii_lowercase().as_str() {
            "zsh" => Some(Self::Zsh),
            "pwsh" | "powershell" => Some(Self::Pwsh),
            _ => None,
        }
    }
}

/// FZF options derived from the palette and L5 glyphs.
pub fn fzf_options(theme: &ResolvedTheme) -> String {
    let palette = &theme.palette;
    let fzf = theme.overrides.as_ref().and_then(|overrides| overrides.fzf.as_ref());
    let prompt = fzf
        .and_then(|fzf| fzf.prompt.clone())
        .map(|value| crate::escape::sanitize_text(&value, 8))
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "> ".to_string());
    let pointer = fzf
        .and_then(|fzf| fzf.pointer.clone())
        .map(|value| crate::escape::sanitize_text(&value, 4))
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| ">".to_string());
    let marker = fzf
        .and_then(|fzf| fzf.marker.clone())
        .map(|value| crate::escape::sanitize_text(&value, 4))
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "*".to_string());
    let border = fzf
        .and_then(|fzf| fzf.border)
        .map(|border| border.as_str())
        .unwrap_or("sharp");

    format!(
        "--border={border} --prompt={prompt:?} --pointer={pointer:?} --marker={marker:?} \
         --color=bg:{base},bg+:{surface},fg:{text},fg+:{bright},hl:{accent},hl+:{accent2},\
info:{muted},prompt:{accent},pointer:{accent},marker:{success},spinner:{info},\
header:{info},border:{border_color},label:{muted},query:{text}",
        base = palette.surfaces.base,
        surface = palette.surfaces.surface0,
        text = palette.text.primary,
        bright = palette.text.secondary,
        accent = palette.accents.primary,
        accent2 = palette.accents.secondary,
        muted = palette.text.muted,
        success = palette.semantic.success,
        info = palette.semantic.info,
        border_color = palette.surfaces.surface2,
    )
}

/// `EZA_COLORS` value.
pub fn eza_colors(theme: &ResolvedTheme) -> String {
    let palette = &theme.palette;
    format!(
        "di={dir}:ln={link}:ex={exec}:fi={file}:pi={fifo}:so={socket}:bd={block}:cd={char}:or={orphan}",
        dir = palette.accents.tertiary,
        link = palette.semantic.info,
        exec = palette.semantic.success,
        file = palette.text.primary,
        fifo = palette.semantic.warning,
        socket = palette.semantic.warning,
        block = palette.semantic.warning,
        char = palette.semantic.warning,
        orphan = palette.semantic.error,
    )
}

/// Renders `generated/env.zsh`.
pub fn env_zsh(theme: &ResolvedTheme, config_dir: &Path, policy: PromptPolicy, aliases: bool) -> String {
    let config_dir = config_dir.to_string_lossy().into_owned();
    let mut out = String::with_capacity(2048);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n\n", theme.id, theme.profile));
    out.push_str(&format!("export KISEKI_THEME={}\n", shell_single_quote(theme.id.as_str())));
    out.push_str(&format!(
        "export KISEKI_THEME_NAME={}\n",
        shell_single_quote(&theme.name)
    ));
    out.push_str(&format!(
        "export KISEKI_PROFILE={}\n",
        shell_single_quote(theme.profile.as_str())
    ));
    out.push_str(&format!(
        "export KISEKI_CONFIG_DIR={}\n",
        shell_single_quote(&config_dir)
    ));
    out.push_str(&format!(
        "export KISEKI_ACCENT_PRIMARY={}\n",
        shell_single_quote(&theme.palette.accents.primary.to_hex())
    ));
    out.push_str(&format!(
        "export KISEKI_ACCENT_SECONDARY={}\n",
        shell_single_quote(&theme.palette.accents.secondary.to_hex())
    ));
    out.push_str(&format!(
        "export FZF_DEFAULT_OPTS={}\n",
        shell_single_quote(&fzf_options(theme))
    ));
    out.push_str(&format!("export EZA_COLORS={}\n", shell_single_quote(&eza_colors(theme))));

    match policy {
        PromptPolicy::ManagedTemplate => {
            out.push_str(&format!(
                "export POSH_THEME={}\n",
                shell_single_quote(&format!("{config_dir}/generated/prompt.omp.json"))
            ));
            // Initialize Oh My Posh ONCE per shell session (when POSH_CONFIG is
            // not yet bound to POSH_THEME). Subsequent `kiseki use`/`crt`/`live`
            // updates overwrite `prompt.omp.json` in place, so OMP picks up the
            // new theme automatically without re-running `oh-my-posh init zsh`
            // inside `precmd` (which would flash `zsh>` and spawn a subprocess).
            out.push_str("if (( $+commands[oh-my-posh] )); then\n");
            out.push_str("  if [[ \"${POSH_CONFIG:-}\" != \"$POSH_THEME\" ]]; then\n");
            out.push_str("    eval \"$(oh-my-posh init zsh --config \"$POSH_THEME\")\"\n");
            out.push_str("  fi\n");
            out.push_str("else\n");
            out.push_str(&format!(
                "  export STARSHIP_CONFIG={}\n",
                shell_single_quote(&format!("{config_dir}/generated/starship-palette.toml"))
            ));
            out.push_str("fi\n");
        }
        PromptPolicy::PaletteOnly => {
            out.push_str(&format!(
                "export KISEKI_STARSHIP_PALETTE={}\n",
                shell_single_quote(&format!("{config_dir}/generated/starship-palette.toml"))
            ));
        }
        PromptPolicy::Disabled => {}
    }

    out.push('\n');
    out.push_str("# zsh-syntax-highlighting: only recolour, never rebind.\n");
    out.push_str("if (( ${+ZSH_HIGHLIGHT_STYLES} )); then\n");
    for (slot, color) in [
        ("command", theme.syntax.function),
        ("builtin", theme.syntax.function),
        ("alias", theme.syntax.string),
        ("function", theme.syntax.function),
        ("path", theme.syntax.property),
        ("comment", theme.syntax.comment),
        ("string", theme.syntax.string),
        ("unknown-token", theme.syntax.invalid),
        ("reserved-word", theme.syntax.keyword),
        ("redirection", theme.syntax.operator),
    ] {
        out.push_str(&format!(
            "  ZSH_HIGHLIGHT_STYLES[{slot}]={}\n",
            shell_single_quote(&format!("fg={color}"))
        ));
    }
    out.push_str("fi\n");

    if aliases {
        out.push_str("\n# Opt-in `--aliases`: new commands only, nothing is shadowed.\n");
        out.push_str("alias theme='kiseki use'\n");
        out.push_str("alias themes='kiseki pick'\n");
    }

    // One-time Fastfetch system-info greeting on fresh interactive terminal tabs
    // (never inside VS Code, non-TTY subshells, KISEKI_NO_FETCH=1, or precmd).
    out.push_str("\n# Auto-greeting once per new interactive terminal session.\n");
    out.push_str("if [[ -t 1 ]] && [[ -z \"${KISEKI_NO_FETCH:-}\" ]] && [[ -z \"${KISEKI_GREETED:-}\" ]] \\\n");
    out.push_str("  && [[ -z \"${VSCODE_INJECTION:-}\" ]] && [[ \"${TERM_PROGRAM:-}\" != \"vscode\" ]]; then\n");
    out.push_str("  export KISEKI_GREETED=1\n");
    out.push_str("  if (( $+commands[fastfetch] )) && [[ -r \"$KISEKI_CONFIG_DIR/generated/fastfetch.jsonc\" ]]; then\n");
    out.push_str("    fastfetch --config \"$KISEKI_CONFIG_DIR/generated/fastfetch.jsonc\"\n");
    out.push_str("  fi\n");
    out.push_str("fi\n");

    out
}

/// Renders `generated/env.ps1`.
pub fn env_ps1(theme: &ResolvedTheme, config_dir: &Path, policy: PromptPolicy) -> String {
    let config_dir = config_dir.to_string_lossy().into_owned();
    let mut out = String::with_capacity(2048);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n\n", theme.id, theme.profile));
    out.push_str(&format!(
        "$env:KISEKI_THEME = {}\n",
        powershell_single_quote(theme.id.as_str())
    ));
    out.push_str(&format!(
        "$env:KISEKI_THEME_NAME = {}\n",
        powershell_single_quote(&theme.name)
    ));
    out.push_str(&format!(
        "$env:KISEKI_PROFILE = {}\n",
        powershell_single_quote(theme.profile.as_str())
    ));
    out.push_str(&format!(
        "$env:KISEKI_CONFIG_DIR = {}\n",
        powershell_single_quote(&config_dir)
    ));
    out.push_str(&format!(
        "$env:FZF_DEFAULT_OPTS = {}\n",
        powershell_single_quote(&fzf_options(theme))
    ));
    out.push_str(&format!(
        "$env:EZA_COLORS = {}\n",
        powershell_single_quote(&eza_colors(theme))
    ));

    match policy {
        PromptPolicy::ManagedTemplate => {
            out.push_str(&format!(
                "$env:POSH_THEME = {}\n",
                powershell_single_quote(&format!("{config_dir}\\generated\\prompt.omp.json"))
            ));
            out.push_str(&format!(
                "$env:STARSHIP_CONFIG = {}\n",
                powershell_single_quote(&format!("{config_dir}\\generated\\starship-palette.toml"))
            ));
        }
        PromptPolicy::PaletteOnly => {
            out.push_str(&format!(
                "$env:KISEKI_STARSHIP_PALETTE = {}\n",
                powershell_single_quote(&format!("{config_dir}\\generated\\starship-palette.toml"))
            ));
        }
        PromptPolicy::Disabled => {}
    }

    out.push('\n');
    out.push_str("# PSReadLine: visual colours only. No key handlers, no aliases.\n");
    out.push_str("if (Get-Command Set-PSReadLineOption -ErrorAction SilentlyContinue) {\n");
    out.push_str("    Set-PSReadLineOption -Colors @{\n");
    for (option, color) in [
        ("Command", theme.syntax.function),
        ("Comment", theme.syntax.comment),
        ("String", theme.syntax.string),
        ("Operator", theme.syntax.operator),
        ("Variable", theme.syntax.variable),
        ("Parameter", theme.syntax.parameter),
        ("Number", theme.syntax.number),
        ("Type", theme.syntax.type_),
        ("Keyword", theme.syntax.keyword),
        ("Error", theme.syntax.invalid),
        ("Default", theme.palette.text.primary),
    ] {
        out.push_str(&format!(
            "        {option} = {}\n",
            powershell_single_quote(&color.to_hex())
        ));
    }
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

/// The block installed into `.zshrc` / `$PROFILE`.
///
/// The body is intentionally tiny: one source at startup, then a hook that
/// reads one integer per prompt. `read`, `[[`, `source` and `add-zsh-hook` are
/// all zsh builtins, so the no-change path forks nothing.
pub fn zsh_init_script(config_dir: &Path, aliases: bool) -> String {
    let dir = shell_single_quote(&config_dir.to_string_lossy());
    let mut out = String::new();
    out.push_str("_KISEKI_CONFIG_DIR=");
    out.push_str(&dir);
    out.push('\n');
    out.push_str("_KISEKI_LOADED_GEN=\"\"\n");
    out.push_str("if [[ -r \"$_KISEKI_CONFIG_DIR/generated/env.zsh\" ]]; then\n");
    out.push_str("  source \"$_KISEKI_CONFIG_DIR/generated/env.zsh\"\n");
    out.push_str("  if [[ -r \"$_KISEKI_CONFIG_DIR/state.gen\" ]]; then\n");
    out.push_str("    read -r _KISEKI_LOADED_GEN < \"$_KISEKI_CONFIG_DIR/state.gen\"\n");
    out.push_str("  fi\n");
    out.push_str("fi\n");
    out.push_str("_kiseki_sync_hook() {\n");
    out.push_str("  local gen\n");
    out.push_str("  if [[ -r \"$_KISEKI_CONFIG_DIR/state.gen\" ]]; then\n");
    out.push_str("    read -r gen < \"$_KISEKI_CONFIG_DIR/state.gen\" || return 0\n");
    out.push_str("    if [[ \"$gen\" != \"$_KISEKI_LOADED_GEN\" ]]; then\n");
    out.push_str("      source \"$_KISEKI_CONFIG_DIR/generated/env.zsh\"\n");
    out.push_str("      _KISEKI_LOADED_GEN=\"$gen\"\n");
    out.push_str("    fi\n");
    out.push_str("  fi\n");
    out.push_str("}\n");
    out.push_str("autoload -Uz add-zsh-hook\n");
    out.push_str("add-zsh-hook precmd _kiseki_sync_hook\n");
    if aliases {
        out.push_str("alias theme='kiseki use'\n");
        out.push_str("alias themes='kiseki pick'\n");
    }
    out
}

/// The block installed into a PowerShell profile.
///
/// `[System.IO.File]::ReadAllText` and string comparison run in-process, so the
/// no-change path creates no child process (unlike `& kiseki ...`).
pub fn pwsh_init_script(config_dir: &Path, aliases: bool) -> String {
    let dir = powershell_single_quote(&config_dir.to_string_lossy());
    let mut out = String::new();
    out.push_str("$script:KisekiConfigDir = ");
    out.push_str(&dir);
    out.push('\n');
    out.push_str("$script:KisekiGenFile = Join-Path $script:KisekiConfigDir 'state.gen'\n");
    out.push_str("$script:KisekiLoadedGen = ''\n");
    out.push_str("$script:KisekiEnvFile = Join-Path $script:KisekiConfigDir 'generated\\env.ps1'\n");
    out.push_str("if (Test-Path $script:KisekiEnvFile) { . $script:KisekiEnvFile }\n");
    out.push_str("if (Test-Path $script:KisekiGenFile) {\n");
    out.push_str("    $script:KisekiLoadedGen = [System.IO.File]::ReadAllText($script:KisekiGenFile).Trim()\n");
    out.push_str("}\n");
    out.push_str("function global:_KisekiSyncHook {\n");
    out.push_str("    if (-not (Test-Path $script:KisekiGenFile)) { return }\n");
    out.push_str("    $gen = [System.IO.File]::ReadAllText($script:KisekiGenFile).Trim()\n");
    out.push_str("    if ($gen -ne $script:KisekiLoadedGen) {\n");
    out.push_str("        . $script:KisekiEnvFile\n");
    out.push_str("        $script:KisekiLoadedGen = $gen\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out.push_str("if (-not (Test-Path variable:global:_KisekiOriginalPrompt)) {\n");
    out.push_str("    $global:_KisekiOriginalPrompt = $function:prompt\n");
    out.push_str("}\n");
    out.push_str("function global:prompt {\n");
    out.push_str("    _KisekiSyncHook\n");
    out.push_str("    if ($null -ne $global:_KisekiOriginalPrompt) {\n");
    out.push_str("        & $global:_KisekiOriginalPrompt\n");
    out.push_str("    } else {\n");
    out.push_str("        \"PS $($executionContext.SessionState.Path.CurrentLocation)$('>' * ($nestedPromptLevel + 1)) \"\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    if aliases {
        // Forwarding functions keep `theme <id>` / `themes` working: a plain
        // `Set-Alias` cannot inject the `use` / `pick` subcommands.
        out.push_str("function global:theme { kiseki use @args }\n");
        out.push_str("function global:themes { kiseki pick @args }\n");
    }
    out
}

/// Convenience dispatcher used by `kiseki shell-init`.
pub fn init_script(shell: ShellKind, config_dir: &Path, aliases: bool) -> String {
    match shell {
        ShellKind::Zsh => zsh_init_script(config_dir, aliases),
        ShellKind::Pwsh => pwsh_init_script(config_dir, aliases),
    }
}

/// Static lint: reject any behaviour mutation in generated shell code.
pub fn lint_shell_artifacts(content: &str) -> Vec<kiseki_types::Diagnostic> {
    let mut diagnostics = Vec::new();
    const FORBIDDEN: &[&str] = &[
        "alias cat=",
        "alias ls=",
        "alias grep=",
        "alias cd=",
        "zoxide init",
        "bindkey ",
        "Set-PSReadLineKeyHandler",
        "Remove-Item Alias:",
        "function global:cat",
        "function global:ls",
        "function global:grep",
    ];
    for forbidden in FORBIDDEN {
        if content.contains(forbidden) {
            diagnostics.push(kiseki_types::Diagnostic::error(
                "adapter.shell.behaviour-mutation",
                format!("generated shell code must not contain {forbidden:?}"),
            ));
        }
    }
    diagnostics
}

#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::{ThemePack, ResolvedTheme};
    use kiseki_types::RenderingProfile;
    use std::path::PathBuf;

    fn theme() -> ResolvedTheme {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json")).unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json")).unwrap(),
        };
        ResolvedTheme::from_pack(&pack, RenderingProfile::Balanced)
    }

    fn config_dir() -> PathBuf {
        PathBuf::from("/home/zz/.config/kiseki")
    }

    #[test]
    fn zsh_env_sets_palette_and_prompt_but_no_behaviour_aliases() {
        let content = env_zsh(&theme(), &config_dir(), PromptPolicy::ManagedTemplate, false);
        assert!(content.contains("export KISEKI_THEME='nerv-eva'"));
        assert!(content.contains("export KISEKI_PROFILE='balanced'"));
        assert!(content.contains("export FZF_DEFAULT_OPTS='"));
        assert!(content.contains("export EZA_COLORS='"));
        assert!(content.contains("export POSH_THEME='/home/zz/.config/kiseki/generated/prompt.omp.json'"));
        assert!(content.contains("export STARSHIP_CONFIG="));
        assert!(content.contains("ZSH_HIGHLIGHT_STYLES[command]"));
        assert!(!content.contains("alias cat"));
        assert!(!content.contains("alias ls"));
        assert!(!content.contains("alias grep"));
        assert!(!content.contains("zoxide"));
        assert!(!content.contains("bindkey"));
        assert!(lint_shell_artifacts(&content).is_empty());
    }

    #[test]
    fn aliases_are_opt_in_and_never_shadow_standard_commands() {
        let content = env_zsh(&theme(), &config_dir(), PromptPolicy::ManagedTemplate, true);
        assert!(content.contains("alias theme='kiseki use'"));
        assert!(content.contains("alias themes='kiseki pick'"));
        assert!(!content.contains("alias cat="));
        assert!(!content.contains("alias ls="));
    }

    #[test]
    fn palette_only_does_not_override_the_users_prompt() {
        let content = env_zsh(&theme(), &config_dir(), PromptPolicy::PaletteOnly, false);
        assert!(!content.contains("export POSH_THEME"));
        assert!(!content.contains("export STARSHIP_CONFIG"));
        assert!(content.contains("KISEKI_STARSHIP_PALETTE"));
    }

    #[test]
    fn disabled_emits_no_prompt_paths() {
        let content = env_zsh(&theme(), &config_dir(), PromptPolicy::Disabled, false);
        assert!(!content.contains("POSH_THEME"));
        assert!(!content.contains("STARSHIP"));
    }

    #[test]
    fn zsh_hook_is_zero_fork_on_the_no_change_path() {
        let script = zsh_init_script(&config_dir(), false);
        assert!(script.contains("read -r gen < \"$_KISEKI_CONFIG_DIR/state.gen\""));
        assert!(script.contains("if [[ \"$gen\" != \"$_KISEKI_LOADED_GEN\" ]]"));
        assert!(script.contains("add-zsh-hook precmd _kiseki_sync_hook"));
        // No command substitution or external process on the hot path. `||`
        // and `[[` are shell builtins, not forks.
        for forbidden in ["$(", "`", "kiseki status", "exec ", "fork", "command "] {
            assert!(!script.contains(forbidden), "{forbidden} found in\n{script}");
        }
        assert!(lint_shell_artifacts(&script).is_empty());
    }

    #[test]
    fn pwsh_hook_reads_the_gen_file_with_dotnet_not_a_subprocess() {
        let script = pwsh_init_script(&config_dir(), false);
        assert!(script.contains("[System.IO.File]::ReadAllText($script:KisekiGenFile)"));
        assert!(script.contains("if ($gen -ne $script:KisekiLoadedGen)"));
        assert!(script.contains("function global:prompt"));
        for forbidden in ["& kiseki", "Start-Process", "Set-PSReadLineKeyHandler", "Remove-Item Alias:"] {
            assert!(!script.contains(forbidden), "{forbidden} found in\n{script}");
        }
        assert!(lint_shell_artifacts(&script).is_empty());
    }

    #[test]
    fn pwsh_aliases_are_forwarding_functions() {
        let script = pwsh_init_script(&config_dir(), true);
        // A bare alias cannot append the `use` / `pick` subcommand.
        assert!(script.contains("function global:theme { kiseki use @args }"), "{script}");
        assert!(script.contains("function global:themes { kiseki pick @args }"), "{script}");
        assert!(!script.contains("Set-Alias -Name theme"), "{script}");
        assert!(!script.contains("Set-Alias -Name themes"), "{script}");
        assert!(lint_shell_artifacts(&script).is_empty());
    }

    #[test]
    fn pwsh_aliases_are_opt_in() {
        let script = pwsh_init_script(&config_dir(), false);
        assert!(!script.contains("function global:theme"));
        assert!(!script.contains("function global:themes"));
    }

    #[test]
    fn hostile_config_paths_are_quoted() {
        let hostile = PathBuf::from("/tmp/it's $(evil) `id`; rm -rf ~");
        let zsh = zsh_init_script(&hostile, false);
        // The whole path is inside a single-quoted string, so `$(...)`, `;` and
        // backticks are literal; only the embedded quote needs escaping.
        assert!(zsh.contains(r"'/tmp/it'\''s $(evil) `id`; rm -rf ~'"), "{zsh}");
        let pwsh = pwsh_init_script(&hostile, false);
        assert!(pwsh.contains("'/tmp/it''s $(evil) `id`; rm -rf ~'"), "{pwsh}");
    }

    #[test]
    fn ps1_env_sets_colors_without_key_handlers() {
        let content = env_ps1(&theme(), &config_dir(), PromptPolicy::ManagedTemplate);
        assert!(content.contains("$env:KISEKI_THEME = 'nerv-eva'"));
        assert!(content.contains("Set-PSReadLineOption -Colors"));
        assert!(!content.contains("Set-PSReadLineKeyHandler"));
        assert!(!content.contains("Set-Alias"));
        assert!(lint_shell_artifacts(&content).is_empty());
    }

    #[test]
    fn fzf_options_carry_palette_and_glyphs() {
        let options = fzf_options(&theme());
        assert!(options.contains("--color=bg:#0B090A"));
        assert!(options.contains("hl:#F06A22"));
        assert!(options.contains("--border=sharp"));
        assert!(options.contains("02"));
    }

    #[test]
    fn lint_catches_behaviour_mutations() {
        let diagnostics = lint_shell_artifacts("alias cat='bat'\nzoxide init zsh\n");
        assert_eq!(diagnostics.len(), 2);
        assert!(diagnostics.iter().all(kiseki_types::Diagnostic::is_fatal));
    }
}

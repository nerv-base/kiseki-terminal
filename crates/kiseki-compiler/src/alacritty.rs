//! Alacritty `alacritty.toml` generation and safe `general.import` patching (RFC-0003 §4).
//!
//! Alacritty supports palette, typography, opacity, blur, padding and cursor
//! shape; wallpapers and shaders degrade gracefully.

use std::path::Path;

use kiseki_schema::{CursorShape, ResolvedTheme};
use kiseki_types::Diagnostic;

use crate::escape::toml_string;
use crate::marker::{find_marker_block, remove_marker_block, upsert_marker_block};

/// Renders `generated/alacritty.toml`.
pub fn render(
    theme: &ResolvedTheme,
    font_families: &[String],
    macos_font_scale: bool,
) -> String {
    let palette = &theme.palette;
    let ansi = &palette.ansi;
    let mut out = String::with_capacity(2048);
    out.push_str("# === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("# theme: {} | profile: {}\n\n", theme.id, theme.profile));

    out.push_str("[colors.primary]\n");
    out.push_str(&format!("background = {}\n", toml_string(&palette.surfaces.base.to_hex())));
    out.push_str(&format!("foreground = {}\n", toml_string(&palette.text.primary.to_hex())));

    out.push_str("\n[colors.cursor]\n");
    out.push_str(&format!("cursor = {}\n", toml_string(&palette.interaction.cursor.to_hex())));
    out.push_str(&format!("text = {}\n", toml_string(&palette.interaction.cursor_text.to_hex())));

    out.push_str("\n[colors.selection]\n");
    out.push_str(&format!("background = {}\n", toml_string(&palette.interaction.selection_bg.to_hex())));
    out.push_str(&format!("text = {}\n", toml_string(&palette.interaction.selection_fg.to_hex())));

    out.push_str("\n[colors.normal]\n");
    for (name, color) in [
        ("black", ansi.black),
        ("red", ansi.red),
        ("green", ansi.green),
        ("yellow", ansi.yellow),
        ("blue", ansi.blue),
        ("magenta", ansi.magenta),
        ("cyan", ansi.cyan),
        ("white", ansi.white),
    ] {
        out.push_str(&format!("{name} = {}\n", toml_string(&color.to_hex())));
    }

    out.push_str("\n[colors.bright]\n");
    for (name, color) in [
        ("black", ansi.bright_black),
        ("red", ansi.bright_red),
        ("green", ansi.bright_green),
        ("yellow", ansi.bright_yellow),
        ("blue", ansi.bright_blue),
        ("magenta", ansi.bright_magenta),
        ("cyan", ansi.bright_cyan),
        ("white", ansi.bright_white),
    ] {
        out.push_str(&format!("{name} = {}\n", toml_string(&color.to_hex())));
    }

    // Typography
    if !font_families.is_empty() || theme.typography.size_pt.is_some() {
        out.push_str("\n[font]\n");
        if let Some(size) = theme.typography.size_pt {
            let effective = if macos_font_scale {
                (size * 1.25 * 2.0).round() / 2.0
            } else {
                size
            };
            out.push_str(&format!("size = {effective:.2}\n"));
        }
        if let Some(primary) = font_families.first() {
            out.push_str(&format!("\n[font.normal]\nfamily = {}\n", toml_string(primary)));
        }
    }

    // Window
    out.push_str("\n[window]\n");
    out.push_str(&format!("opacity = {:.4}\n", theme.window_opacity.clamp(0.0, 1.0)));
    if let Some(window) = theme.atmosphere.window.as_ref() {
        out.push_str(&format!("blur = {}\n", window.blur));
        if let Some(padding) = window.padding {
            out.push_str(&format!("padding = {{ x = {}, y = {} }}\n", padding.x, padding.y));
        }
    }

    // Cursor
    let cursor = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.cursor_shape)
        .unwrap_or(CursorShape::Block);
    let shape = match cursor {
        CursorShape::Block | CursorShape::BlockHollow => "Block",
        CursorShape::Bar => "Beam",
        CursorShape::Underline => "Underline",
    };
    out.push_str(&format!("\n[cursor.style]\nshape = {}\n", toml_string(shape)));

    out
}

/// Copyable manual import snippet for `[general]` in `alacritty.toml`.
pub fn manual_hint(generated_path: &Path) -> String {
    format!("[general]\nimport = [{}]", toml_string(&generated_path.to_string_lossy()))
}

/// Inserts or updates `general.import` in an existing `alacritty.toml` while
/// preserving user comments and formatting.
///
/// Validates the resulting document with `toml::from_str`; if an unusual TOML
/// layout cannot be safely patched, returns `Err(manual_hint)`.
pub fn patch_alacritty_toml(
    original: &str,
    begin: &str,
    end: &str,
    generated_path: &Path,
) -> std::result::Result<String, String> {
    let quoted_path = toml_string(&generated_path.to_string_lossy());
    let marker_body = format!("[general]\nimport = [{quoted_path}]");

    // Case 1: already owns a marker block — update in place.
    if find_marker_block(original, begin, end).is_some() {
        let updated = upsert_marker_block(original, begin, end, &marker_body);
        if toml::from_str::<toml::Value>(&updated).is_ok() {
            return Ok(updated);
        }
        return Err(manual_hint(generated_path));
    }

    // Case 2: already references the exact path outside markers.
    if original.contains(&quoted_path) {
        return Ok(original.to_string());
    }

    // Check whether `[general]` already exists in the document.
    let parsed: toml::Value = toml::from_str(original).map_err(|_| manual_hint(generated_path))?;
    let has_general = parsed.get("general").is_some();

    if !has_general {
        let updated = upsert_marker_block(original, begin, end, &marker_body);
        if toml::from_str::<toml::Value>(&updated).is_ok() {
            return Ok(updated);
        }
        return Err(manual_hint(generated_path));
    }

    // Case 3: `[general]` exists — splice into existing `[general]` table.
    let newline = if original.contains("\r\n") { "\r\n" } else { "\n" };
    let lines: Vec<&str> = original.lines().collect();
    let general_idx = lines
        .iter()
        .position(|line| line.trim() == "[general]")
        .ok_or_else(|| manual_hint(generated_path))?;

    // Find the end of `[general]` (next `[section]` header or EOF).
    let section_end = lines[(general_idx + 1)..]
        .iter()
        .position(|line| {
            let t = line.trim();
            t.starts_with('[') && !t.starts_with("[[") || t.starts_with("[[")
        })
        .map(|rel| general_idx + 1 + rel)
        .unwrap_or(lines.len());

    // Look for a single-line `import = [...]` inside `[general]`.
    let import_idx = ((general_idx + 1)..section_end).find(|&i| {
        let t = lines[i].trim();
        t.starts_with("import") && t[6..].trim_start().starts_with('=')
    });

    let mut out_lines: Vec<String> = lines.iter().map(|s| (*s).to_string()).collect();
    if let Some(idx) = import_idx {
        let line = &out_lines[idx];
        // Support single-line `import = [...]` cleanly.
        if let (Some(open), Some(close)) = (line.find('['), line.rfind(']')) {
            if open < close {
                let inner = line[(open + 1)..close].trim();
                let new_inner = if inner.is_empty() {
                    quoted_path.clone()
                } else {
                    format!("{}, {}", inner.trim_end_matches(',').trim(), quoted_path)
                };
                let replacement = format!("{}[{}]{}", &line[..open], new_inner, &line[(close + 1)..]);
                out_lines[idx] = replacement;
            } else {
                return Err(manual_hint(generated_path));
            }
        } else {
            return Err(manual_hint(generated_path));
        }
    } else {
        out_lines.insert(general_idx + 1, format!("import = [{quoted_path}]"));
    }

    let mut result = out_lines.join(newline);
    if original.ends_with('\n') || !result.is_empty() {
        result.push_str(newline);
    }
    if toml::from_str::<toml::Value>(&result).is_ok() {
        Ok(result)
    } else {
        Err(manual_hint(generated_path))
    }
}

/// Removes Kiseki's import from `alacritty.toml` (both marker-block and inline forms).
pub fn unhook_alacritty_toml(
    original: &str,
    begin: &str,
    end: &str,
    generated_path: &Path,
) -> String {
    if find_marker_block(original, begin, end).is_some() {
        return remove_marker_block(original, begin, end);
    }
    let quoted_path = toml_string(&generated_path.to_string_lossy());
    if !original.contains(&quoted_path) {
        return original.to_string();
    }
    let newline = if original.contains("\r\n") { "\r\n" } else { "\n" };
    let mut out_lines = Vec::new();
    for line in original.lines() {
        if line.contains(&quoted_path) {
            if let (Some(open), Some(close)) = (line.find('['), line.rfind(']')) {
                if open < close {
                    let items: Vec<&str> = line[(open + 1)..close]
                        .split(',')
                        .map(str::trim)
                        .filter(|item| !item.is_empty() && *item != quoted_path)
                        .collect();
                    if items.is_empty() {
                        // Drop the entire `import = [...]` line if we were the only item.
                        continue;
                    }
                    out_lines.push(format!(
                        "{}[{}]{}",
                        &line[..open],
                        items.join(", "),
                        &line[(close + 1)..]
                    ));
                    continue;
                }
            }
        }
        out_lines.push(line.to_string());
    }
    let mut result = out_lines.join(newline);
    if original.ends_with('\n') && !result.is_empty() {
        result.push_str(newline);
    }
    result
}

/// Static validation: must parse as valid TOML and never touch `[terminal.shell]` or `[keyboard]`.
pub fn lint(content: &str) -> Vec<Diagnostic> {
    let mut diagnostics = Vec::new();
    let parsed: toml::Value = match toml::from_str(content) {
        Ok(value) => value,
        Err(error) => {
            diagnostics.push(Diagnostic::error(
                "adapter.alacritty.invalid-toml",
                format!("generated alacritty.toml is not valid TOML: {error}"),
            ));
            return diagnostics;
        }
    };
    if parsed.get("keyboard").is_some() {
        diagnostics.push(Diagnostic::error(
            "adapter.alacritty.non-visual-key",
            "generated alacritty.toml must not set `[keyboard]`",
        ));
    }
    if parsed
        .get("terminal")
        .and_then(|t| t.get("shell"))
        .is_some()
    {
        diagnostics.push(Diagnostic::error(
            "adapter.alacritty.non-visual-key",
            "generated alacritty.toml must not set `[terminal.shell]`",
        ));
    }
    diagnostics
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::marker::{MARKER_BEGIN, MARKER_END};
    use kiseki_schema::ThemePack;
    use kiseki_types::RenderingProfile;

    fn theme() -> ResolvedTheme {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json"))
                .unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json"))
                .unwrap(),
        };
        ResolvedTheme::from_pack(&pack, RenderingProfile::Balanced)
    }

    #[test]
    fn renders_valid_alacritty_toml() {
        let content = render(&theme(), &["JetBrainsMono Nerd Font".to_string()], false);
        assert!(content.contains("[colors.primary]"));
        assert!(content.contains("background = \"#0B090A\""));
        assert!(content.contains("[font.normal]"));
        assert!(lint(&content).is_empty());
    }

    #[test]
    fn patches_both_missing_and_existing_general_section() {
        let gen = Path::new("/home/zz/.config/kiseki/generated/alacritty.toml");

        // No `[general]` -> marker block.
        let bare = "[window]\ndecorations = \"full\"\n";
        let patched = patch_alacritty_toml(bare, MARKER_BEGIN, MARKER_END, gen).unwrap();
        assert!(patched.contains(MARKER_BEGIN));
        assert!(toml::from_str::<toml::Value>(&patched).is_ok());
        assert_eq!(unhook_alacritty_toml(&patched, MARKER_BEGIN, MARKER_END, gen), bare);

        // Existing `[general]` with existing `import`.
        let existing = "[general]\nimport = [\"~/.config/alacritty/custom.toml\"]\n";
        let patched2 = patch_alacritty_toml(existing, MARKER_BEGIN, MARKER_END, gen).unwrap();
        assert!(patched2.contains("custom.toml"));
        assert!(patched2.contains("generated/alacritty.toml"));
        assert!(toml::from_str::<toml::Value>(&patched2).is_ok());
        let restored = unhook_alacritty_toml(&patched2, MARKER_BEGIN, MARKER_END, gen);
        assert!(restored.contains("custom.toml"));
        assert!(!restored.contains("generated/alacritty.toml"));
    }
}

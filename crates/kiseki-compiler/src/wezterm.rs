//! WezTerm `wezterm.lua` generation and safe host patching (RFC-0003 §4).
//!
//! The generated Lua file returns a pure visual applier `function(config)` that
//! sets only colour palette, typography, opacity, blur, padding, cursor style
//! and optional wallpaper. It never touches `keys`, `default_prog`, `launch_menu`,
//! or spawns external processes.

use std::path::Path;

use kiseki_schema::{CursorShape, ResolvedTheme};
use kiseki_types::Diagnostic;

use crate::marker::{find_marker_block, remove_marker_block, upsert_marker_block};

/// Lua opening marker for v2 anchors in `wezterm.lua`.
pub const LUA_MARKER_BEGIN: &str = "-- >>> kiseki >>>";
/// Lua closing marker for v2 anchors in `wezterm.lua`.
pub const LUA_MARKER_END: &str = "-- <<< kiseki <<<";

/// Escapes a string as a Lua double-quoted literal.
pub fn lua_string(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len() + 2);
    out.push('"');
    for ch in raw.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if ch.is_control() => {}
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// Renders `generated/wezterm.lua`.
pub fn render(
    theme: &ResolvedTheme,
    font_families: &[String],
    wallpaper: Option<&Path>,
    macos_font_scale: bool,
) -> String {
    let palette = &theme.palette;
    let ui = &theme.ui;
    let ansi = palette.ansi.as_indexed();
    let mut out = String::with_capacity(2560);
    out.push_str("-- === Auto-generated by Kiseki Terminal (DO NOT EDIT) ===\n");
    out.push_str(&format!("-- theme: {} | profile: {}\n", theme.id, theme.profile));
    out.push_str("local wezterm = require 'wezterm'\n\n");
    out.push_str("return function(config)\n");
    out.push_str("  if type(config) ~= 'table' then return end\n\n");

    // Colours
    out.push_str("  config.colors = {\n");
    out.push_str(&format!("    foreground = {},\n", lua_string(&palette.text.primary.to_hex())));
    out.push_str(&format!("    background = {},\n", lua_string(&palette.surfaces.base.to_hex())));
    out.push_str(&format!("    cursor_bg = {},\n", lua_string(&palette.interaction.cursor.to_hex())));
    out.push_str(&format!("    cursor_fg = {},\n", lua_string(&palette.interaction.cursor_text.to_hex())));
    out.push_str(&format!("    cursor_border = {},\n", lua_string(&palette.interaction.cursor.to_hex())));
    out.push_str(&format!("    selection_bg = {},\n", lua_string(&palette.interaction.selection_bg.to_hex())));
    out.push_str(&format!("    selection_fg = {},\n", lua_string(&palette.interaction.selection_fg.to_hex())));
    out.push_str(&format!("    split = {},\n", lua_string(&ui.border.to_hex())));
    out.push_str("    ansi = {\n");
    for color in &ansi[0..8] {
        out.push_str(&format!("      {},\n", lua_string(&color.to_hex())));
    }
    out.push_str("    },\n");
    out.push_str("    brights = {\n");
    for color in &ansi[8..16] {
        out.push_str(&format!("      {},\n", lua_string(&color.to_hex())));
    }
    out.push_str("    },\n");
    out.push_str("    tab_bar = {\n");
    out.push_str(&format!("      background = {},\n", lua_string(&palette.surfaces.crust.to_hex())));
    out.push_str(&format!(
        "      active_tab = {{ bg_color = {}, fg_color = {} }},\n",
        lua_string(&ui.tab_active_bg.to_hex()),
        lua_string(&ui.tab_active_fg.to_hex())
    ));
    out.push_str(&format!(
        "      inactive_tab = {{ bg_color = {}, fg_color = {} }},\n",
        lua_string(&ui.tab_inactive_bg.to_hex()),
        lua_string(&ui.tab_inactive_fg.to_hex())
    ));
    out.push_str("    },\n");
    out.push_str("  }\n\n");

    // Typography
    if !font_families.is_empty() {
        let list = font_families
            .iter()
            .map(|family| lua_string(family))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("  config.font = wezterm.font_with_fallback({{ {list} }})\n"));
    }
    if let Some(size) = theme.typography.size_pt {
        let effective = if macos_font_scale {
            (size * 1.25 * 2.0).round() / 2.0
        } else {
            size
        };
        out.push_str(&format!("  config.font_size = {effective:.2}\n"));
    }
    if theme.typography.ligatures == Some(false) {
        out.push_str("  config.harfbuzz_features = { 'calt=0', 'clig=0', 'liga=0' }\n");
    }

    // Window & cursor
    out.push_str(&format!(
        "  config.window_background_opacity = {:.4}\n",
        theme.window_opacity.clamp(0.0, 1.0)
    ));
    if let Some(window) = theme.atmosphere.window.as_ref() {
        if window.blur {
            out.push_str("  config.macos_window_background_blur = 20\n");
        }
        if let Some(padding) = window.padding {
            out.push_str(&format!(
                "  config.window_padding = {{ left = {}, right = {}, top = {}, bottom = {} }}\n",
                padding.x, padding.x, padding.y, padding.y
            ));
        }
    }
    let cursor = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.cursor_shape)
        .unwrap_or(CursorShape::Block);
    let blink = theme
        .overrides
        .as_ref()
        .and_then(|overrides| overrides.terminal.as_ref())
        .and_then(|terminal| terminal.cursor_blink)
        .unwrap_or(false);
    out.push_str(&format!(
        "  config.default_cursor_style = {}\n",
        lua_string(wezterm_cursor(cursor, blink))
    ));

    // Wallpaper
    if let Some(wallpaper) = wallpaper.filter(|_| theme.wallpaper_opacity.is_none_or(|o| o > 0.0)) {
        let opacity = theme.wallpaper_opacity.unwrap_or(0.5).clamp(0.0, 1.0);
        out.push_str(&format!(
            "  config.window_background_image = {}\n",
            lua_string(&wallpaper.to_string_lossy())
        ));
        out.push_str(&format!(
            "  config.window_background_image_hsb = {{ brightness = {:.4}, hue = 1.0, saturation = 1.0 }}\n",
            opacity.max(0.05)
        ));
    } else {
        out.push_str("  config.window_background_image = nil\n");
    }

    out.push_str("end\n");
    out
}

fn wezterm_cursor(shape: CursorShape, blink: bool) -> &'static str {
    match (shape, blink) {
        (CursorShape::Block | CursorShape::BlockHollow, true) => "BlinkingBlock",
        (CursorShape::Block | CursorShape::BlockHollow, false) => "SteadyBlock",
        (CursorShape::Bar, true) => "BlinkingBar",
        (CursorShape::Bar, false) => "SteadyBar",
        (CursorShape::Underline, true) => "BlinkingUnderline",
        (CursorShape::Underline, false) => "SteadyUnderline",
    }
}

/// Finds a safe top-level `return <ident>` statement near the end of `wezterm.lua`.
///
/// Inline `return { ... }` tables and arbitrary expressions are deliberately
/// rejected so Kiseki never corrupts non-trivial Lua configs (RFC-0003 §4).
pub fn find_return_ident(source: &str) -> Option<(usize, String)> {
    let mut offset = 0usize;
    let mut found: Option<(usize, String)> = None;
    for line in source.split_inclusive('\n') {
        let stripped = line.split("--").next().unwrap_or(line).trim();
        if let Some(rest) = stripped.strip_prefix("return") {
            let valid_sep = rest.chars().next().is_some_and(char::is_whitespace);
            if valid_sep {
                let ident = rest.trim().trim_end_matches(';').trim();
                if is_lua_ident(ident) {
                    found = Some((offset, ident.to_string()));
                }
            }
        }
        offset += line.len();
    }
    found
}

fn is_lua_ident(raw: &str) -> bool {
    let mut chars = raw.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    if !chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_') {
        return false;
    }
    !matches!(
        raw,
        "nil" | "true" | "false" | "function" | "if" | "for" | "while" | "do" | "end" | "return"
    )
}

/// Renders the safe `pcall(dofile, ...)` hook snippet for `ident`.
pub fn hook_body(generated_path: &Path, ident: &str) -> String {
    let path = lua_string(&generated_path.to_string_lossy());
    format!(
        "do local ok, apply = pcall(dofile, {path}); if ok and type(apply) == 'function' then apply({ident}) end end"
    )
}

/// Copyable 2-line manual integration snippet shown when auto-patching is unsafe.
pub fn manual_hint(generated_path: &Path) -> String {
    let path = lua_string(&generated_path.to_string_lossy());
    format!(
        "local ok, apply = pcall(dofile, {path}); if ok then apply(config) end"
    )
}

/// True when `wezterm.lua` can be safely anchored without risking syntax breakage.
pub fn can_patch_wezterm_lua(source: &str) -> bool {
    if source.trim().is_empty() {
        return true;
    }
    find_marker_block(source, LUA_MARKER_BEGIN, LUA_MARKER_END).is_some()
        || find_return_ident(source).is_some()
}

/// Inserts or updates the `pcall(dofile, ...)` marker block in `wezterm.lua`.
///
/// Returns `Err(manual_hint)` when the file structure does not end with a simple
/// `return <ident>` statement so callers degrade cleanly to `RenderOnly`.
pub fn patch_wezterm_lua(
    source: &str,
    begin: &str,
    end: &str,
    generated_path: &Path,
) -> std::result::Result<String, String> {
    if source.trim().is_empty() {
        let mut starter = String::from("local wezterm = require 'wezterm'\nlocal config = wezterm.config_builder()\n");
        let body = hook_body(generated_path, "config");
        starter = upsert_marker_block(&starter, begin, end, &body);
        starter.push_str("\nreturn config\n");
        return Ok(starter);
    }

    if find_marker_block(source, begin, end).is_some() {
        let without = remove_marker_block(source, begin, end);
        let ident = find_return_ident(&without)
            .map(|(_, ident)| ident)
            .unwrap_or_else(|| "config".to_string());
        let body = hook_body(generated_path, &ident);
        return Ok(upsert_marker_block(source, begin, end, &body));
    }

    let Some((return_offset, ident)) = find_return_ident(source) else {
        return Err(manual_hint(generated_path));
    };
    let newline = if source.contains("\r\n") { "\r\n" } else { "\n" };
    let body = hook_body(generated_path, &ident);
    let block = format!("{begin}{newline}{body}{newline}{end}{newline}");

    let mut out = String::with_capacity(source.len() + block.len() + 2);
    out.push_str(&source[..return_offset]);
    if !out.is_empty() && !out.ends_with('\n') {
        out.push_str(newline);
    }
    out.push_str(&block);
    out.push_str(&source[return_offset..]);
    Ok(out)
}

/// Static lint: reject executable Lua primitives or keybinding mutations.
pub fn lint(content: &str) -> Vec<Diagnostic> {
    let mut diagnostics = Vec::new();
    const FORBIDDEN: &[&str] = &[
        "os.execute",
        "io.popen",
        "config.keys",
        "default_prog",
        "launch_menu",
    ];
    for forbidden in FORBIDDEN {
        if content.contains(forbidden) {
            diagnostics.push(Diagnostic::error(
                "adapter.wezterm.forbidden",
                format!("generated wezterm.lua must not contain {forbidden:?}"),
            ));
        }
    }
    diagnostics
}

#[cfg(test)]
mod tests {
    use super::*;
    use kiseki_schema::ThemePack;
    use kiseki_types::RenderingProfile;
    use std::path::PathBuf;

    fn theme(profile: RenderingProfile) -> ResolvedTheme {
        let pack = ThemePack {
            manifest: serde_json::from_str(include_str!("../../../themes/nerv-eva/manifest.json"))
                .unwrap(),
            tokens: serde_json::from_str(include_str!("../../../themes/nerv-eva/tokens.json"))
                .unwrap(),
        };
        ResolvedTheme::from_pack(&pack, profile)
    }

    #[test]
    fn renders_clean_lua_module() {
        let lua = render(
            &theme(RenderingProfile::Balanced),
            &["JetBrainsMono Nerd Font".to_string()],
            Some(&PathBuf::from("/themes/nerv-eva/assets/wallpaper.png")),
            false,
        );
        assert!(lua.contains("return function(config)"));
        assert!(lua.contains("background = \"#0B090A\""));
        assert!(lua.contains("wezterm.font_with_fallback"));
        assert!(lua.contains("window_background_image = \"/themes/nerv-eva/assets/wallpaper.png\""));
        assert!(lint(&lua).is_empty());
    }

    #[test]
    fn patches_before_return_ident_and_is_idempotent() {
        let src = "local wezterm = require 'wezterm'\nlocal cfg = wezterm.config_builder()\ncfg.font_size = 13\nreturn cfg\n";
        let gen = Path::new("/home/zz/.config/kiseki/generated/wezterm.lua");
        let once = patch_wezterm_lua(src, LUA_MARKER_BEGIN, LUA_MARKER_END, gen).unwrap();
        assert!(once.contains("apply(cfg)"));
        assert!(once.find("apply(cfg)").unwrap() < once.find("return cfg").unwrap());

        let twice = patch_wezterm_lua(&once, LUA_MARKER_BEGIN, LUA_MARKER_END, gen).unwrap();
        assert_eq!(once, twice);

        let unhooked = remove_marker_block(&once, LUA_MARKER_BEGIN, LUA_MARKER_END);
        assert_eq!(unhooked, src);
    }

    #[test]
    fn refuses_inline_table_return_instead_of_corrupting() {
        let src = "return {\n  font_size = 14,\n}\n";
        assert!(!can_patch_wezterm_lua(src));
        let err = patch_wezterm_lua(
            src,
            LUA_MARKER_BEGIN,
            LUA_MARKER_END,
            Path::new("/cfg/generated/wezterm.lua"),
        )
        .unwrap_err();
        assert!(err.contains("pcall(dofile"));
    }
}
